  function cubicEaseInOut(t) {
    return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
  }

  function clampViewBox(box) {
    const rawW = Number(box && box[2]) || 960;
    const w = Math.max(240, Math.min(960, rawW));
    const h = w * ASPECT;
    const rawX = Number(box && box[0]) || 0;
    const rawY = Number(box && box[1]) || 0;
    const x = Math.max(0, Math.min(960 - w, rawX));
    const y = Math.max(0, Math.min(440 - h, rawY));
    return [x, y, w, h];
  }

  function formatNum(v) {
    return Math.abs(v - Math.round(v)) < 0.02 ? String(Math.round(v)) : v.toFixed(1);
  }

  function formatViewBox(box) {
    const b = clampViewBox(box);
    return `${formatNum(b[0])} ${formatNum(b[1])} ${formatNum(b[2])} ${formatNum(b[3])}`;
  }

  function nodeTargetViewBox(node, zoomFactor) {
    if (!node) return OVERVIEW_BOX.slice();
    const z = Math.max(1.2, Math.min(3.4, Number(zoomFactor) || 2.15));
    const w = 960 / z;
    const h = 440 / z;
    return clampViewBox([node.x - w / 2, node.y - h / 2, w, h]);
  }

  function zoomViewBox(currentBox, factor) {
    const cur = clampViewBox(currentBox || OVERVIEW_BOX);
    const z = Number(factor) || 1;
    const cx = cur[0] + cur[2] / 2;
    const cy = cur[1] + cur[3] / 2;
    const nextW = Math.max(240, Math.min(960, cur[2] / z));
    const nextH = nextW * ASPECT;
    return clampViewBox([cx - nextW / 2, cy - nextH / 2, nextW, nextH]);
  }

  function cubicSynapsePath(a, b) {
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    if (Math.abs(dx) >= Math.abs(dy) * 0.85) {
      const c1x = Math.round(a.x + dx * 0.44);
      const c1y = Math.round(a.y + dy * 0.08);
      const c2x = Math.round(b.x - dx * 0.44);
      const c2y = Math.round(b.y - dy * 0.08);
      return `M ${a.x} ${a.y} C ${c1x} ${c1y}, ${c2x} ${c2y}, ${b.x} ${b.y}`;
    }
    const c1x = Math.round(a.x + dx * 0.14);
    const c1y = Math.round(a.y + dy * 0.45);
    const c2x = Math.round(b.x - dx * 0.14);
    const c2y = Math.round(b.y - dy * 0.45);
    return `M ${a.x} ${a.y} C ${c1x} ${c1y}, ${c2x} ${c2y}, ${b.x} ${b.y}`;
  }

  function flyToViewBox(svgEl, fromBox, toBox, durationMs, reducedMotion, onFrame, onDone, env) {
    const host = env || (g.window || g);
    const start = clampViewBox(fromBox || OVERVIEW_BOX);
    const end = clampViewBox(toBox || OVERVIEW_BOX);
    const dur = Math.max(0, Number(durationMs) || 0);
    const raf = host && typeof host.requestAnimationFrame === 'function' ? host.requestAnimationFrame.bind(host) : null;
    const caf = host && typeof host.cancelAnimationFrame === 'function' ? host.cancelAnimationFrame.bind(host) : null;

    const applyBox = box => {
      if (svgEl && typeof svgEl.setAttribute === 'function') {
        svgEl.setAttribute('viewBox', formatViewBox(box));
      }
      if (typeof onFrame === 'function') onFrame(box);
    };

    if (reducedMotion || dur === 0 || !raf) {
      applyBox(end);
      if (typeof onDone === 'function') onDone(end);
      return function noopCancel() {};
    }

    const nowFn = () => (host.performance && typeof host.performance.now === 'function' ? host.performance.now() : Date.now());
    const t0 = nowFn();
    let rafId = null;
    let cancelled = false;

    const tick = ts => {
      if (cancelled) return;
      const nowTs = typeof ts === 'number' && ts >= t0 ? ts : nowFn();
      const rawT = Math.min(1, Math.max(0, (nowTs - t0) / dur));
      const e = cubicEaseInOut(rawT);
      const curr = [
        start[0] + (end[0] - start[0]) * e,
        start[1] + (end[1] - start[1]) * e,
        start[2] + (end[2] - start[2]) * e,
        start[3] + (end[3] - start[3]) * e
      ];
      applyBox(curr);
      if (rawT < 1) {
        rafId = raf(tick);
      } else {
        rafId = null;
        applyBox(end);
        if (typeof onDone === 'function') onDone(end);
      }
    };

    rafId = raf(tick);
    return function cancelFly() {
      cancelled = true;
      if (rafId !== null && caf) caf(rafId);
      rafId = null;
    };
  }

  function captureFlipRects(container) {
    const rects = new Map();
    if (!container || typeof container.querySelectorAll !== 'function') return rects;
    let nodes = [];
    try { nodes = container.querySelectorAll('[data-morph-key]'); } catch (_) { return rects; }
    for (let i = 0; i < nodes.length; i++) {
      const el = nodes[i];
      if (!el || typeof el.getBoundingClientRect !== 'function') continue;
      const key = el.getAttribute ? el.getAttribute('data-morph-key') : (el.dataset && el.dataset.morphKey);
      if (!key) continue;
      const r = el.getBoundingClientRect();
      if (r && r.width > 0 && r.height > 0) {
        rects.set(key, { left: r.left, top: r.top, width: r.width, height: r.height });
      }
    }
    return rects;
  }

  function playFlipTransition(container, firstRects, reducedMotion, registerTimer, env, registerCancel) {
    if (reducedMotion || !firstRects || !firstRects.size || !container || typeof container.querySelectorAll !== 'function') {
      return 0;
    }
    let nodes = [];
    try { nodes = container.querySelectorAll('[data-morph-key]'); } catch (_) { return 0; }
    const inverted = [];
    for (let i = 0; i < nodes.length; i++) {
      const el = nodes[i];
      if (!el || !el.style || typeof el.getBoundingClientRect !== 'function') continue;
      const key = el.getAttribute ? el.getAttribute('data-morph-key') : (el.dataset && el.dataset.morphKey);
      const first = key ? firstRects.get(key) : null;
      if (!first) continue;
      const last = el.getBoundingClientRect();
      if (!last || !(last.width > 0 && last.height > 0)) continue;
      const dx = first.left - last.left;
      const dy = first.top - last.top;
      const sx = first.width / last.width;
      const sy = first.height / last.height;
      if (Math.abs(dx) < 0.5 && Math.abs(dy) < 0.5 && Math.abs(sx - 1) < 0.01 && Math.abs(sy - 1) < 0.01) continue;
      el.style.transition = 'none';
      el.style.transformOrigin = 'top left';
      el.style.transform = `translate3d(${dx.toFixed(2)}px, ${dy.toFixed(2)}px, 0) scale(${sx.toFixed(3)}, ${sy.toFixed(3)})`;
      inverted.push(el);
    }
    if (!inverted.length) return 0;

    const host = env || (g.window || g);
    const raf = host && typeof host.requestAnimationFrame === 'function' ? host.requestAnimationFrame.bind(host) : null;
    const caf = host && typeof host.cancelAnimationFrame === 'function' ? host.cancelAnimationFrame.bind(host) : null;
    let flipRafId = null;
    let cancelled = false;

    const resetStyles = () => {
      for (let i = 0; i < inverted.length; i++) {
        const el = inverted[i];
        if (!el || !el.style) continue;
        if (el.classList && typeof el.classList.remove === 'function') el.classList.remove('is-flipping');
        el.style.transition = '';
        el.style.transform = '';
        el.style.transformOrigin = '';
      }
    };

    const cancelFlip = () => {
      cancelled = true;
      if (flipRafId !== null) {
        if (caf) caf(flipRafId);
        flipRafId = null;
      }
      resetStyles();
    };

    const runPlay = () => {
      flipRafId = null;
      if (typeof registerCancel === 'function') registerCancel(null);
      if (cancelled) return;
      for (let i = 0; i < inverted.length; i++) {
        const el = inverted[i];
        void el.offsetWidth;
        if (el.classList && typeof el.classList.add === 'function') el.classList.add('is-flipping');
        el.style.transition = 'transform 560ms cubic-bezier(0.22, 1, 0.36, 1), opacity 420ms ease';
        el.style.transform = 'translate3d(0, 0, 0) scale(1, 1)';
      }
      if (typeof registerTimer === 'function') {
        registerTimer(() => {
          if (!cancelled) resetStyles();
        }, 600);
      }
    };

    if (raf) {
      flipRafId = raf(runPlay);
      if (typeof registerCancel === 'function') registerCancel(cancelFlip);
    } else {
      runPlay();
    }
    return inverted.length;
  }

